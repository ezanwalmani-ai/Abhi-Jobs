import React, { useState, useMemo } from 'react';
import { motion } from 'motion/react';
import { CandidateProfile } from '../../../types';
import { ResumeData } from '../../../types/resume';
import { buildPersonalizedChatGptPrompt } from '../../../services/resumeAiAssistant';
import {
  parseStructuredResumeText,
  ParsedResumeResult,
} from '../../../services/resumeParserService';
import { ParsedResumeReviewPanel } from './ParsedResumeReviewPanel';
import { EASE_PREMIUM } from '../../../lib/motion';
import {
  ArrowLeft,
  Copy,
  Check,
  ExternalLink,
  ClipboardPaste,
  Trash2,
  Sparkles,
  MessageSquareText,
  ArrowRight,
  AlertCircle,
} from 'lucide-react';

interface ChatGptResumeWorkflowProps {
  candidate?: CandidateProfile | null;
  onBack: () => void;
  onConfirmImport: (data: Partial<ResumeData>, goTo: 'wizard' | 'templates') => void;
}

export const ChatGptResumeWorkflow: React.FC<ChatGptResumeWorkflowProps> = ({
  candidate,
  onBack,
  onConfirmImport,
}) => {
  // Step A inputs (pre-populated honestly from candidate profile if present)
  const [fullName, setFullName] = useState(candidate?.name || '');
  const [targetRole, setTargetRole] = useState(
    candidate?.desiredRole || candidate?.currentRole || ''
  );
  const [location, setLocation] = useState(
    [candidate?.city, candidate?.state].filter(Boolean).join(', ') || candidate?.location || ''
  );
  const [email, setEmail] = useState(candidate?.email || '');
  const [phone, setPhone] = useState(candidate?.phone || '');
  const [experienceSummary, setExperienceSummary] = useState(() =>
    (candidate?.experiences || [])
      .map(
        (e) =>
          `${e.jobTitle} at ${e.company} (${e.startDate} - ${e.current ? 'Present' : e.endDate}): ${e.description}`
      )
      .join('\n')
  );
  const [educationSummary, setEducationSummary] = useState(() =>
    (candidate?.education || [])
      .map(
        (e) =>
          `${e.qualification}${e.fieldOfStudy ? ` in ${e.fieldOfStudy}` : ''} - ${e.institution} (${e.startYear} - ${e.endYear})`
      )
      .join('\n')
  );
  const [skillsList, setSkillsList] = useState((candidate?.skills || []).join(', '));
  const [additionalNotes, setAdditionalNotes] = useState('');

  const [copiedPrompt, setCopiedPrompt] = useState(false);

  // Step B paste-back area
  const [pastedContent, setPastedContent] = useState('');
  const [pasteError, setPasteError] = useState<string | null>(null);

  // Step C & D parsed confirmation state
  const [parsedResult, setParsedResult] = useState<ParsedResumeResult | null>(null);

  const personalizedPrompt = useMemo(
    () =>
      buildPersonalizedChatGptPrompt({
        fullName,
        targetRole,
        location,
        email,
        phone,
        experienceSummary,
        educationSummary,
        skillsList,
        additionalNotes,
      }),
    [
      fullName,
      targetRole,
      location,
      email,
      phone,
      experienceSummary,
      educationSummary,
      skillsList,
      additionalNotes,
    ]
  );

  const handleCopyPrompt = async () => {
    try {
      await navigator.clipboard.writeText(personalizedPrompt);
      setCopiedPrompt(true);
      setTimeout(() => setCopiedPrompt(false), 2500);
    } catch {
      // Fallback select & copy
      const ta = document.createElement('textarea');
      ta.value = personalizedPrompt;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand('copy');
      document.body.removeChild(ta);
      setCopiedPrompt(true);
      setTimeout(() => setCopiedPrompt(false), 2500);
    }
  };

  const handlePasteClipboard = async () => {
    setPasteError(null);
    try {
      const text = await navigator.clipboard.readText();
      if (!text.trim()) {
        setPasteError('Your clipboard appears empty. Copy your generated resume from ChatGPT first.');
        return;
      }
      setPastedContent(text);
    } catch {
      setPasteError(
        'Browser clipboard access was blocked. Click inside the text box and press Ctrl+V (or Cmd+V) to paste.'
      );
    }
  };

  const handleImportContent = () => {
    setPasteError(null);
    if (pastedContent.trim().length < 25) {
      setPasteError('Please paste the full resume content generated by ChatGPT before importing.');
      return;
    }
    const parsed = parseStructuredResumeText(pastedContent);
    setParsedResult(parsed);
  };

  if (parsedResult) {
    return (
      <div className="space-y-5">
        <button
          type="button"
          onClick={onBack}
          className="inline-flex items-center gap-1.5 text-xs sm:text-sm font-semibold text-[#778397] hover:text-[#102B4E] cursor-pointer"
        >
          <ArrowLeft className="w-4 h-4" />
          <span>Back to Starting Options</span>
        </button>

        <ParsedResumeReviewPanel
          parsed={parsedResult}
          sourceLabel="ChatGPT Generated Content"
          onBack={() => setParsedResult(null)}
          onConfirm={onConfirmImport}
        />
      </div>
    );
  }

  return (
    <motion.div
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.35, ease: EASE_PREMIUM }}
      className="space-y-6"
    >
      <div className="flex items-center justify-between">
        <button
          type="button"
          onClick={onBack}
          className="inline-flex items-center gap-1.5 text-xs sm:text-sm font-semibold text-[#778397] hover:text-[#102B4E] cursor-pointer"
        >
          <ArrowLeft className="w-4 h-4" />
          <span>Back to Starting Options</span>
        </button>
      </div>

      {/* Intro Banner */}
      <div className="bg-white rounded-3xl border border-[#E5EAF0] p-6 sm:p-8 shadow-2xs space-y-3">
        <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-[#F47A24]/10 text-[#102B4E] text-xs font-bold">
          <MessageSquareText className="w-3.5 h-3.5 text-[#F47A24]" />
          <span>Guided Copy-Prompt &amp; Paste-Back Workflow</span>
        </div>
        <h2 className="text-2xl sm:text-3xl font-extrabold text-[#102B4E] tracking-tight">
          Create Your Resume with ChatGPT
        </h2>
        <p className="text-xs sm:text-sm text-[#778397] max-w-2xl leading-relaxed">
          Not sure how to write a professional resume? Let ChatGPT help you organize your experience and create strong resume content.
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* STEP A — Prepare Personalized ChatGPT Prompt */}
        <div className="lg:col-span-6 bg-white rounded-3xl border border-[#E5EAF0] p-5 sm:p-6 shadow-2xs space-y-5">
          <div className="flex items-center gap-3 pb-3 border-b border-[#F0F3F7]">
            <span className="w-8 h-8 rounded-xl bg-[#102B4E] text-white text-xs font-extrabold flex items-center justify-center shrink-0">
              A
            </span>
            <div>
              <h3 className="text-base font-extrabold text-[#102B4E]">
                Prepare Your Personalized Prompt
              </h3>
              <p className="text-xs text-[#778397]">
                Enter your real facts below — the prompt instructs ChatGPT never to invent experience or dates.
              </p>
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
            <label className="space-y-1">
              <span className="font-semibold text-[#253449]">Full Name</span>
              <input
                type="text"
                value={fullName}
                onChange={(e) => setFullName(e.target.value)}
                placeholder="e.g. Priya Sharma"
                className="w-full px-3 py-2.5 rounded-xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden min-h-[42px]"
              />
            </label>
            <label className="space-y-1">
              <span className="font-semibold text-[#253449]">Target Job Role</span>
              <input
                type="text"
                value={targetRole}
                onChange={(e) => setTargetRole(e.target.value)}
                placeholder="e.g. Financial Analyst"
                className="w-full px-3 py-2.5 rounded-xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden min-h-[42px]"
              />
            </label>
            <label className="space-y-1">
              <span className="font-semibold text-[#253449]">Email</span>
              <input
                type="email"
                value={email}
                onChange={(e) => setEmail(e.target.value)}
                placeholder="you@example.com"
                className="w-full px-3 py-2.5 rounded-xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden min-h-[42px]"
              />
            </label>
            <label className="space-y-1">
              <span className="font-semibold text-[#253449]">Location &amp; Phone</span>
              <input
                type="text"
                value={location}
                onChange={(e) => setLocation(e.target.value)}
                placeholder="City, State"
                className="w-full px-3 py-2.5 rounded-xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden min-h-[42px]"
              />
            </label>
          </div>

          <div className="space-y-3 text-xs">
            <label className="block space-y-1">
              <span className="font-semibold text-[#253449]">
                Your Actual Work Experience / Internships
              </span>
              <textarea
                rows={3}
                value={experienceSummary}
                onChange={(e) => setExperienceSummary(e.target.value)}
                placeholder="Briefly list companies, job titles, dates, and what you worked on..."
                className="w-full p-3 rounded-xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden"
              />
            </label>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              <label className="block space-y-1">
                <span className="font-semibold text-[#253449]">Education</span>
                <textarea
                  rows={2}
                  value={educationSummary}
                  onChange={(e) => setEducationSummary(e.target.value)}
                  placeholder="Degree, college, graduation year..."
                  className="w-full p-3 rounded-xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden"
                />
              </label>

              <label className="block space-y-1">
                <span className="font-semibold text-[#253449]">Core Skills</span>
                <textarea
                  rows={2}
                  value={skillsList}
                  onChange={(e) => setSkillsList(e.target.value)}
                  placeholder="Comma-separated real skills..."
                  className="w-full p-3 rounded-xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden"
                />
              </label>
            </div>

            <label className="block space-y-1">
              <span className="font-semibold text-[#253449]">
                Certifications, Projects, Languages or Achievements (optional)
              </span>
              <input
                type="text"
                value={additionalNotes}
                onChange={(e) => setAdditionalNotes(e.target.value)}
                placeholder="Any notable projects, certifications, or languages..."
                className="w-full px-3 py-2.5 rounded-xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden min-h-[42px]"
              />
            </label>
          </div>

          {/* Generated Prompt Preview */}
          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <span className="text-[11px] font-bold uppercase tracking-wider text-[#778397] flex items-center gap-1">
                <Sparkles className="w-3.5 h-3.5 text-[#F47A24]" />
                <span>Ready-to-Use ChatGPT Prompt</span>
              </span>
            </div>
            <pre className="p-3.5 rounded-2xl bg-[#081D36] text-slate-100 text-[11px] leading-relaxed whitespace-pre-wrap max-h-48 overflow-y-auto font-mono border border-[#102B4E]">
              {personalizedPrompt}
            </pre>
          </div>

          <div className="flex flex-col sm:flex-row items-stretch sm:items-center gap-2.5 pt-1">
            <button
              type="button"
              onClick={handleCopyPrompt}
              className="flex-1 min-h-[46px] px-4 py-2.5 rounded-xl bg-[#102B4E] hover:bg-[#081D36] text-white text-xs sm:text-sm font-bold inline-flex items-center justify-center gap-2 transition-colors cursor-pointer"
            >
              {copiedPrompt ? (
                <>
                  <Check className="w-4 h-4 text-emerald-400" />
                  <span>Prompt Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4 text-[#F47A24]" />
                  <span>Copy Prompt</span>
                </>
              )}
            </button>

            <a
              href="https://chatgpt.com/"
              target="_blank"
              rel="noopener noreferrer"
              className="flex-1 min-h-[46px] px-4 py-2.5 rounded-xl bg-[#F47A24] hover:bg-[#DE6816] text-white text-xs sm:text-sm font-bold inline-flex items-center justify-center gap-2 transition-colors"
            >
              <span>Open ChatGPT</span>
              <ExternalLink className="w-4 h-4" />
            </a>
          </div>
        </div>

        {/* STEP B — Paste Your Resume Content */}
        <div className="lg:col-span-6 bg-white rounded-3xl border border-[#E5EAF0] p-5 sm:p-6 shadow-2xs space-y-5">
          <div className="flex items-center gap-3 pb-3 border-b border-[#F0F3F7]">
            <span className="w-8 h-8 rounded-xl bg-[#F47A24] text-white text-xs font-extrabold flex items-center justify-center shrink-0">
              B
            </span>
            <div>
              <h3 className="text-base font-extrabold text-[#102B4E]">
                Paste Your Resume Content
              </h3>
              <p className="text-xs text-[#778397]">
                Copy the resume content generated by ChatGPT and paste it here. ABHI JOBS will organize it into your resume.
              </p>
            </div>
          </div>

          <div className="flex flex-wrap items-center justify-between gap-2">
            <button
              type="button"
              onClick={handlePasteClipboard}
              className="min-h-[38px] px-3.5 py-2 rounded-xl bg-[#F6F8FB] hover:bg-[#102B4E] hover:text-white border border-[#E5EAF0] text-[#102B4E] text-xs font-semibold inline-flex items-center gap-1.5 transition-colors cursor-pointer"
            >
              <ClipboardPaste className="w-3.5 h-3.5" />
              <span>Paste from Clipboard</span>
            </button>

            {pastedContent && (
              <button
                type="button"
                onClick={() => {
                  setPastedContent('');
                  setPasteError(null);
                }}
                className="min-h-[38px] px-3 py-2 rounded-xl text-rose-600 hover:bg-rose-50 text-xs font-semibold inline-flex items-center gap-1.5 cursor-pointer"
              >
                <Trash2 className="w-3.5 h-3.5" />
                <span>Clear Content</span>
              </button>
            )}
          </div>

          <textarea
            rows={15}
            value={pastedContent}
            onChange={(e) => {
              setPastedContent(e.target.value);
              if (pasteError) setPasteError(null);
            }}
            placeholder={`Paste the structured resume content from ChatGPT here...\n\nExample headings recognized automatically:\nPERSONAL INFORMATION\nPROFESSIONAL SUMMARY\nWORK EXPERIENCE\nEDUCATION\nSKILLS\nCERTIFICATIONS\nPROJECTS\nLANGUAGES\nACHIEVEMENTS`}
            className="w-full p-4 rounded-2xl border border-[#E5EAF0] bg-[#F6F8FB] focus:bg-white focus:border-[#102B4E] focus:outline-hidden text-xs sm:text-sm text-[#253449] leading-relaxed font-mono"
          />

          {pasteError && (
            <div className="p-3 rounded-xl bg-rose-50 border border-rose-200 text-rose-800 text-xs flex items-start gap-2">
              <AlertCircle className="w-4 h-4 shrink-0 mt-0.5" />
              <span>{pasteError}</span>
            </div>
          )}

          <button
            type="button"
            onClick={handleImportContent}
            disabled={!pastedContent.trim()}
            className="w-full min-h-[48px] px-6 py-3 rounded-xl bg-[#102B4E] hover:bg-[#081D36] disabled:opacity-45 text-white text-sm font-bold inline-flex items-center justify-center gap-2 shadow-xs transition-all cursor-pointer"
          >
            <span>Import Content &amp; Organize Sections</span>
            <ArrowRight className="w-4 h-4 text-[#F47A24]" />
          </button>
        </div>
      </div>
    </motion.div>
  );
};

export default ChatGptResumeWorkflow;
